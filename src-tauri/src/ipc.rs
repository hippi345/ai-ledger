//! Typed IPC between the Rust backend and the React UI.
//!
//! Commands are registered once in [`builder`]. The TypeScript bindings in
//! `ui/src/bindings.ts` are generated from it with tauri-specta, and a test
//! fails if the committed file is out of date, so the UI never calls a
//! command with the wrong shape.

use serde::Serialize;
use specta::Type;
use tauri_specta::{collect_commands, Builder};

/// Where the generated bindings live, relative to this crate.
pub const BINDINGS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../ui/src/bindings.ts");

const HEADER: &str =
    "// Generated by tauri-specta from src-tauri/src/ipc.rs. Do not edit by hand.\n\
// Regenerate with: cargo test -p ai-ledger --test ipc -- --ignored\n";

/// Basic facts about the running app, shown in the About box.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct AppInfo {
    pub app_version: String,
    pub core_version: String,
}

/// Returns the app and core library versions.
#[tauri::command]
#[specta::specta]
pub fn app_info() -> AppInfo {
    AppInfo {
        app_version: env!("CARGO_PKG_VERSION").to_owned(),
        core_version: ledger_core::VERSION.to_owned(),
    }
}

/// Event emitted after new usage is stored (spec §7).
pub const INGESTED_EVENT: &str = "ledger://ingested";

/// Payload of [`INGESTED_EVENT`]: which source changed and how much.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct IngestedEvent {
    pub source_id: i64,
    pub inserted: u32,
    pub updated: u32,
}

impl IngestedEvent {
    pub fn new(source_id: i64, s: ledger_core::ingest::IngestStats) -> Self {
        let n = |v: usize| u32::try_from(v).unwrap_or(u32::MAX);
        Self {
            source_id,
            inserted: n(s.inserted),
            updated: n(s.updated),
        }
    }

    /// True when the UI has something new to show.
    pub fn changed(&self) -> bool {
        self.inserted > 0 || self.updated > 0
    }
}

/// The command/event registry shared by the app and the bindings export.
pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        // IPC payloads are JSON, so 64-bit integers already arrive in JS as
        // `number`. Token counts and ids stay far below 2^53.
        .dangerously_cast_bigints_to_number()
        .typ::<IngestedEvent>()
        .commands(collect_commands![
            app_info,
            crate::commands::settings::get_setting,
            crate::commands::settings::set_setting,
            crate::commands::settings::reset_setting,
            crate::commands::settings::list_settings,
            crate::commands::sources::list_sources,
            crate::commands::sources::detect_sources,
            crate::commands::sources::add_source,
            crate::commands::sources::set_source_enabled,
            crate::commands::prices::list_price_overrides,
            crate::commands::prices::set_price_override,
            crate::commands::prices::remove_price_override,
            crate::commands::prices::list_unknown_models,
            crate::autostart::set_launch_at_login,
        ])
}

/// Writes TypeScript bindings for [`builder`] to `path`.
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    builder()
        .export(
            specta_typescript::Typescript::default().header(HEADER),
            path,
        )
        .map_err(|e| e.to_string())
}
